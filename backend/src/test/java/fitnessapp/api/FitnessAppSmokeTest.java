package fitnessapp.api;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.web.servlet.MockMvc;

/**
 * Full-context smoke test: boots the application on H2 (Flyway disabled —
 * schema generated by Hibernate) and verifies the security filter chain
 * rejects unauthenticated access to protected routes.
 *
 * Inline properties are used (not just the test profile) because a host
 * SPRING_DATASOURCE_URL environment variable would otherwise outrank the
 * profile YAML files.
 */
@SpringBootTest(properties = {
        "spring.datasource.url=jdbc:h2:mem:fitnessapp-smoke;DB_CLOSE_DELAY=-1",
        "spring.datasource.username=sa",
        "spring.datasource.password=",
        "spring.jpa.hibernate.ddl-auto=create-drop",
        "spring.flyway.enabled=false"
})
@AutoConfigureMockMvc
class FitnessAppSmokeTest {

    @Autowired
    private MockMvc mockMvc;

    @Test
    void contextBootsAndProtectedRouteRejectsAnonymousAccess() throws Exception {
        mockMvc.perform(get("/api/activities"))
                .andExpect(status().isUnauthorized());
    }
}
